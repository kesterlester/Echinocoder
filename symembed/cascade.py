@dataclass
class Stage:
    """One cyclic stage: Z_p inside Z_R (see the module docstring)."""
    R: int
    p: int
    passed: list                      # input indices passed on (weight kappa/p)
    packed: list                      # input indices placed in Q
    conj: list                        # per packed coordinate: used conjugated
    weight: list                      # per packed coordinate: the weight used (mod R)
    position: list                    # per packed coordinate: its power of x
    shift: int
    W: int
    select: list                      # indices into bursar_output_labels(p, W) of the coefficients output
    out_weights: list                 # weights (mod R/p) of the stage outputs: passed, then selected
    imaginary: list = field(default_factory=list)   # per output: known to be purely imaginary


def plan_stage(weights: list, imaginary: list, R: int, p: int) -> Stage:
    """Plan a cyclic stage for coordinates with the given weights (mod R)."""
    passed = [i for i, k in enumerate(weights) if k % p == 0]
    packed_in = [i for i, k in enumerate(weights) if k % p != 0]
    real, pairs, members = {}, {}, {}
    for i in packed_in:
        k = weights[i] % R
        if k == 0 or 2 * k == R:
            real[k] = real.get(k, 0) + 1
            members.setdefault(("real", k), []).append(i)
        else:
            kk = min(k, R - k)
            pairs[kk] = pairs.get(kk, 0) + 1
            members.setdefault(("pair", kk), []).append(i)
    shift, counts = choose_layout(R, real, pairs) if packed_in else (0, {})
    used = {}                                                     # input index -> (weight used, conjugated)
    for (kind, k), idx in members.items():
        if kind == "real":
            used.update({i: (k, False) for i in idx})
        else:
            n_k = counts.get(k, 0)
            for t, i in enumerate(idx):
                wk = k if t < n_k else R - k
                used[i] = (wk, weights[i] % R != wk)
    position, slot_count = {}, {}
    for i in packed_in:
        wk = used[i][0]
        t = slot_count.get(wk, 0)
        slot_count[wk] = t + 1
        position[i] = (wk + shift) % R + R * t
    packed = sorted(packed_in, key=lambda i: position[i])
    W = max(position.values()) + 1 if packed else 0
    out_weights = [(weights[i] % R) // p for i in passed]
    out_imaginary = [imaginary[i] for i in passed]
    select = []
    if packed:
        occupied = sorted(position.values())
        labels = bursar_output_labels(p, W)
        where = {lab: n for n, lab in enumerate(labels)}
        reach = {0}
        for c in range(1, p + 1):
            reach = {a + b for a in reach for b in occupied}
            for j in sorted(reach):
                if (j - shift * c) % p == 0:
                    select.append(where[(c, j)])
                    out_weights.append(((j - shift * c) % R) // p)
                    out_imaginary.append(False)
    return Stage(R, p, passed, packed, [used[i][1] for i in packed], [used[i][0] for i in packed],
                 [position[i] for i in packed], shift, W, select, out_weights, out_imaginary)


def plan_cascade(weights: list, imaginary: list, r: int, chain: list) -> tuple[list, list, list]:
    """Stages along ``chain`` (factors of r, product r). Returns (stages, final weights, final imaginary flags)."""
    stages, R = [], r
    for p in chain:
        stage = plan_stage(weights, imaginary, R, p)
        stages.append(stage)
        weights, imaginary, R = stage.out_weights, stage.imaginary, R // p
    return stages, weights, imaginary


def final_count(n_coordinates: int, imaginary: list, real_structure: bool) -> int:
    if not real_structure:
        return 2 * n_coordinates
    return sum(1 for f in imaginary if not f) + max(0, 2 * n_coordinates - 1)


def factorisations(r: int):
    """Ordered factorisations of r into factors > 1 (the chains of cyclic subgroups of Z_r)."""
    if r == 1:
        yield []
        return
    for p in range(2, r + 1):
        if r % p == 0:
            for rest in factorisations(r // p):
                yield [p] + rest


@dataclass
class CascadePlan:
    D: list                           # indices (into G) of the dihedral or cyclic subgroup
    h: int                            # index into G
    s: int | None                     # index into G
    r: int
    chain: list
    invariants: np.ndarray            # (n_inv, m) real: D-invariant coordinates, output directly
    base_re: np.ndarray               # (n_base, m) real parts of the base coordinates
    base_im: np.ndarray               # (n_base, m)
    stages: list
    final_imaginary: list
    count: int                        # outputs per D-orbit
    total: int                        # outputs of the embedding


def _base_coordinates(coords: dict) -> tuple[list, list, list]:
    """(exact rows, weights, purely-imaginary flags) of the base coordinates of a graded packing."""
    F = Cyclotomic(coords["L"])
    rows, weights, imaginary = [], [], []
    for k, cs in coords["real"].items():
        for U in cs:
            rows.append(U)
            weights.append(k)
            imaginary.append(bool(np.array_equal(U @ F.conj_matrix.T, -U)))
    for k, basis in coords["pairs"].items():
        for U in basis:
            rows.append(U)
            weights.append(k)
            imaginary.append(False)
    return rows, weights, imaginary


def choose_cascade(index: list, sign: list, elements: tuple, species_blocks, first: int | None = None,
                   partners: int = 4) -> CascadePlan | None:
    """
    Search dihedral (and cyclic) subgroups D = <h, s> (one h per conjugacy class, a few s per h) and chains of cyclic
    subgroups for the fewest outputs. With ``first`` (an index into G), only cascades whose first stage is the
    subgroup generated by that element (an involution) are allowed.
    """
    Ms = matrices(index, sign)
    N, m = len(Ms), Ms[0].shape[0]
    I = np.eye(m)
    involutions = [g for g in range(N) if np.allclose(Ms[g] @ Ms[g], I)]
    best, seen = None, set()
    for h, element in enumerate(elements):
        key = conjugacy_key(element, species_blocks)
        if key in seen and first is None:
            continue
        seen.add(key)
        r = _order(Ms[h])
        if first is not None and (r % 2 or not np.allclose(np.linalg.matrix_power(Ms[h], r // 2), Ms[first])):
            continue
        in_h = {tuple(np.rint(np.linalg.matrix_power(Ms[h], t)).astype(int).ravel()) for t in range(r)}
        cands = [x for x in involutions if np.allclose(Ms[x] @ Ms[h] @ Ms[x], Ms[h].T)
                 and tuple(np.rint(Ms[x]).astype(int).ravel()) not in in_h][:partners] + [None]
        for s in cands:
            D = subgroup(Ms, [h] + ([] if s is None else [s]))
            MD = [Ms[g] for g in D]
            coords = packing_coordinates(MD, D.index(h), None if s is None else D.index(s), True)
            rows, weights, imaginary = _base_coordinates(coords)
            n_inv = len(coords["invariants"])
            for chain in factorisations(coords["r"]):
                if first is not None and (not chain or chain[0] != 2):
                    continue
                stages, final_w, final_im = plan_cascade(weights, imaginary, coords["r"], chain)
                count = n_inv + final_count(len(final_w), final_im, s is not None)
                total = count if len(D) == N else bursar_size(N // len(D), count)
                if best is None or total < best.total:
                    F = Cyclotomic(coords["L"])
                    phi = F.to_complex(np.array(rows, dtype=object).reshape(len(rows), m, F.f)) if rows \
                        else np.zeros((0, m), dtype=complex)
                    inv = np.array(coords["invariants"], dtype=float).reshape(n_inv, m)
                    best = CascadePlan(D, h, s, coords["r"], chain, inv, phi.real.copy(), phi.imag.copy(), stages,
                                       final_im, count, total)
    return best


class _StageModule(nn.Module):
    def __init__(self, stage: Stage, dtype: torch.dtype):
        super().__init__()
        self.register_buffer("passed", torch.tensor(stage.passed, dtype=torch.int64))
        self.register_buffer("packed", torch.tensor(stage.packed, dtype=torch.int64))
        self.register_buffer("conj_sign", torch.tensor([-1.0 if c else 1.0 for c in stage.conj], dtype=dtype))
        angle = np.array([[2 * np.pi * (k * t % stage.p) / stage.p for k in stage.weight] for t in range(stage.p)])
        angle = angle.reshape(stage.p, len(stage.packed))
        self.register_buffer("cos", torch.tensor(np.cos(angle), dtype=dtype))       # zeta_p^(kappa t)
        self.register_buffer("sin", torch.tensor(np.sin(angle), dtype=dtype))
        place = np.zeros((len(stage.packed), max(stage.W, 1)))
        for a, j in enumerate(stage.position):
            place[a, j] = 1.0
        self.register_buffer("place", torch.tensor(place, dtype=dtype))
        self.register_buffer("select", torch.tensor(stage.select, dtype=torch.int64))
        self.has_packed = len(stage.packed) > 0

    def forward(self, re: torch.Tensor, im: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        out_re, out_im = [re[:, self.passed]], [im[:, self.passed]]
        if self.has_packed:
            v_re = re[:, self.packed].unsqueeze(1)                        # (B, 1, n)
            v_im = (im[:, self.packed] * self.conj_sign).unsqueeze(1)
            q_re = (self.cos * v_re - self.sin * v_im) @ self.place       # (B, p, W)
            q_im = (self.sin * v_re + self.cos * v_im) @ self.place
            e_re, e_im = bursar_coefficients_complex(q_re, q_im)
            out_re.append(e_re[:, self.select])
            out_im.append(e_im[:, self.select])
        return torch.cat(out_re, -1), torch.cat(out_im, -1)


class CascadeCore(nn.Module):
    """The cascade for one D-orbit: w (B, m) -> (B, count)."""

    def __init__(self, plan: CascadePlan, dtype: torch.dtype):
        super().__init__()
        self.register_buffer("inv", torch.tensor(plan.invariants, dtype=dtype))
        self.register_buffer("base_re", torch.tensor(plan.base_re, dtype=dtype))
        self.register_buffer("base_im", torch.tensor(plan.base_im, dtype=dtype))
        self.stages = nn.ModuleList([_StageModule(st, dtype) for st in plan.stages])
        self.real_structure = plan.s is not None
        self.register_buffer("keep_re", torch.tensor([i for i, f in enumerate(plan.final_imaginary) if not f],
                                                     dtype=torch.int64))
        self.count = plan.count

    def forward(self, w: torch.Tensor) -> torch.Tensor:
        re, im = w @ self.base_re.T, w @ self.base_im.T
        for stage in self.stages:
            re, im = stage(re, im)
        parts = [w @ self.inv.T] if self.inv.shape[0] else []
        if not self.real_structure:
            parts += [re, im]
        elif re.shape[-1]:
            parts.append(re[:, self.keep_re])
            # Q(x) conj(Q)(x): the y^0 coefficient of (y + Q)(y + conj Q); real for every input.
            q_re = torch.stack([re, re], 1)
            q_im = torch.stack([im, -im], 1)
            e_re, _ = bursar_coefficients_complex(q_re, q_im)
            parts.append(e_re[:, re.shape[-1]:])
        return torch.cat(parts, -1)


class CascadeEmbedding(InvariantEmbedding):
    """embedder="bursar_cascade": the cascade on D-orbits, nested over right cosets of D when D is smaller than G."""

    def __init__(self, n: int, k: int, slots: tuple, index: list, sign: list, dtype: torch.dtype, plan: CascadePlan,
                 reps: list, metric: tuple | None = None, vector_w: bool = True):
        super().__init__(n, k, slots, [index[g] for g in reps], [sign[g] for g in reps], dtype, metric=metric,
                         vector_w=vector_w)
        self.core = CascadeCore(plan, dtype)
        self.n_cosets = len(reps)
        self.output_shape = torch.tensor([plan.total], dtype=torch.int64)

    def forward(self, x) -> torch.Tensor:
        x = self._prepare(x)
        batch_shape = x.shape[:-2]
        out = self.from_w(self.w(x).reshape(-1, self.m))
        return out.reshape(*batch_shape, out.shape[-1])

    def from_w(self, w: torch.Tensor) -> torch.Tensor:
        if self.n_cosets == 1:
            return self.core(w)
        B = w.shape[0]
        w_reps = w[:, self.g_index] * self.g_sign                          # (B, cosets, m)
        inner = self.core(w_reps.reshape(B * self.n_cosets, self.m)).reshape(B, self.n_cosets, self.core.count)
        return bursar_coefficients(inner)


CERTIFICATION_CASCADE = (
    "Level 0 (by construction): cascaded graded embedding. The packed coordinates of a graded packing for the "
    "dihedral (or cyclic) subgroup D = <h, s> are eigen-coordinates of h and are conjugated by s, so the D-orbit of the "
    "packed vector is determined by the vector itself. Each cyclic stage embeds the orbit of its input coordinates "
    "under a cyclic subgroup Z_p by the Bursarial polynomial of p points (injective on multisets by unique "
    "factorisation), with positions congruent to weights plus a shift, so that the rest of <h> multiplies its "
    "outputs by roots of unity and s conjugates them; the conjugation stage embeds {Y, conj Y} by Re Y and Q conj(Q). "
    "So the outputs determine the D-orbit of w; when D is smaller than G, the Bursarial embedding of the multiset over "
    "right cosets Dg determines MS. MS determines L up to G and rotations (up to G and O(k) if parity is in G)."
)


class CascadeMeta:
    """Metadata for embedder="bursar_cascade" (same reading API as the other metadata classes)."""

    def __init__(self, group_spec, k, options, slots, elements, plan: CascadePlan, reps: list, e_dropped: bool):
        self.group_spec, self.k, self.options, self.slots = group_spec, k, options, slots
        self.elements, self.plan, self.reps, self.e_dropped = elements, plan, reps, e_dropped
        self.relations = ()
        self.kept = list(range(plan.total))
        self.echinocoder_commit = _echinocoder_commit()

    certification_level = 0
    labels = property(lambda self: self.group_spec.labels)
    n = property(lambda self: self.group_spec.n)
    m = property(lambda self: len(self.slots))
    N = property(lambda self: len(self.elements))

    @property
    def D(self) -> int:
        return self.plan.total

    @property
    def certification(self) -> str:
        from .meta import CERTIFICATION_E_DROPPED
        return CERTIFICATION_CASCADE + (" " + CERTIFICATION_E_DROPPED if self.e_dropped else "")

    def element_name(self, g) -> str | None:
        return None if g is None else self.elements[g].cycle_notation(self.labels)

    def inner_names(self) -> list[str]:
        p = self.plan
        names = [f"inv[{t}]" for t in range(len(p.invariants))]
        K = len(p.final_imaginary)
        if p.s is None:
            return names + [f"Re Y_{i}" for i in range(K)] + [f"Im Y_{i}" for i in range(K)]
        names += [f"Re Y_{i}" for i, f in enumerate(p.final_imaginary) if not f]
        return names + [f"(Q conj Q)_{j}" for j in range(max(0, 2 * K - 1))]

    def output_names(self) -> list[str]:
        if len(self.reps) == 1:
            return self.inner_names()
        return [f"outer E_{{{c},{j}}}" for c, j in bursar_output_labels(len(self.reps), self.plan.count)]

    def reconstruct_base(self, Y):
        return Y

    def to_dict(self) -> dict:
        p = self.plan
        return {
            "symembed_version": SYMEMBED_VERSION, "echinocoder_commit": self.echinocoder_commit,
            "group_spec": self.group_spec.to_dict(), "k": self.k, "options": self.options.to_dict(),
            "n": self.n, "m": self.m, "multiset_size": self.N, "D": self.D,
            "certification_level": 0, "certification": self.certification,
            "cascade": {"h": self.element_name(p.h), "s": self.element_name(p.s), "r": p.r, "order_D": len(p.D),
                        "chain": p.chain, "per_orbit_outputs": p.count, "cosets": len(self.reps),
                        "stages": [{"R": st.R, "p": st.p, "passed": len(st.passed), "packed": len(st.packed),
                                    "shift": st.shift, "W": st.W, "outputs": len(st.out_weights)} for st in p.stages]},
            "outputs": [{"index": i, "name": nm} for i, nm in enumerate(self.output_names())],
        }

    def to_json(self, **kwargs) -> str:
        return json.dumps(self.to_dict(), **kwargs)

    def latex(self, max_rows: int = 200) -> str:
        p = self.plan
        return (f"\\noindent Cascaded graded embedding: $|G| = {self.N}$, $D = \\langle {self.element_name(p.h)}, "
                f"{self.element_name(p.s) or '-'} \\rangle$ of order {len(p.D)}, chain {p.chain}, {p.count} outputs "
                f"per $D$-orbit, {len(self.reps)} cosets, $D = {self.D}$ outputs. "
                f"Certification: {_latex_text(self.certification)}\n")
