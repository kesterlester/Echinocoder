"""
Cascaded graded embedding (embedder "bursar_cascade"; notes, Section "Cascaded graded embedding").

Let D = <h, s> be a dihedral subgroup of G (s h s = h^-1, or s absent: D = <h> cyclic), and z(w) the packed
coordinates of a graded packing for D: z_a(h.w) = zeta_r^(k_a) z_a(w) and, with s, z_a(s.w) = conj z_a(w). The whole
D-orbit of z(w) is then known from z(w) alone, so it can be embedded in stages along a chain of cyclic subgroups
Z_p1 < Z_p1p2 < ... < Z_r = <h>, followed (with s) by one conjugation stage.

A cyclic stage, for the group Z_R generated by g (the image of h) and its subgroup Z_p generated by g^(R/p), takes
complex coordinates Y_i with weights kappa_i (Y_i(g.w) = zeta_R^kappa_i Y_i(w)) and with Y_i(s.w) = conj Y_i(w).
Coordinates with p | kappa_i are fixed by Z_p and passed on. The others are placed in a polynomial
Q(x) = sum_i Y_i x^(j_i) at positions j_i = kappa_i + shift (mod R) (conjugating a coordinate negates its weight; the
layout is chosen to make Q short, see graded.choose_layout), and the Bursarial polynomial of the Z_p-orbit,
prod_t (y + Q_t(x)) with Q_t = sum_i zeta_p^(kappa_i t) Y_i x^(j_i), determines that orbit (unique factorisation). Its
coefficients E_{c,j} vanish unless j = shift c (mod p), and since g multiplies Q by zeta_R^-shift and substitutes
x -> zeta_R x, g multiplies E_{c,j} by zeta_R^(j - shift c): the outputs are again eigen-coordinates, with weights
(j - shift c)/p modulo R/p, and s still acts on them by conjugation. So the next stage is graded too.

After the last cyclic stage every coordinate is fixed by <h>. The conjugation stage embeds the pair {Y, conj Y}:
Re Y, and the coefficients of the real polynomial Q(x) conj(Q)(x), Q(x) = sum_i Y_i x^i (y + Q)(y + conj Q) =
y^2 + 2 Re Q y + Q conj Q). Without s, Re Y and Im Y are output.

Each stage is injective on its orbits, so the outputs determine the D-orbit of w (Level 0). When D is smaller than G,
the D-orbits of g.w over right cosets Dg are embedded this way and their multiset by a plain Bursarial embedding, as
in nested coset packing.
"""
