"""
Write out, in full, the embeddings produced for very simple cases, for inspection by eye.

Run from the repository root:

    /Users/lester/github/Echinocoder/venv/bin/python -m symembed.explore.simple_cases

This writes, in symembed/docs/explorations/:

* simple_cases.tex, compiled to simple_cases.pdf if pdflatex is available. Each case shows the slots of w, the
  action of G on them, and every Bursarial output E_{c,j} expanded in the d's and e's, except that expansions with
  more than TERM_LIMIT terms are replaced by their term count. Outputs dropped by the safe reductions are marked
  with the identity that justifies dropping them.
* simple_cases_full.txt: every expansion in full, one line per output, with no limit.
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import sympy
import torch

from symembed import EmbeddingOptions, GroupSpec, build_invariant_embedding
from symembed.slots import slot_orbits

# (title, k, spec)
CASES = [
    ("$S(2)$ acting on $(a, b)$, $k = 2$", 2, GroupSpec((("a", "b"),))),
    ("$S(3)$ acting on $(a, b, c)$, $k = 2$", 2, GroupSpec((("a", "b", "c"),))),
    ("$S(2) \\times S(1)$ acting on $(a, b, p)$, $k = 2$", 2, GroupSpec((("a", "b"), ("p",)))),
    ("$S(2)$ acting on $(a, b)$, $k = 1$", 1, GroupSpec((("a", "b"),))),
    ("$S(3)$ acting on $(a, b, c)$, $k = 1$", 1, GroupSpec((("a", "b", "c"),))),
    ("$S(2) \\times S(1)$ acting on $(a, b, p)$, $k = 1$", 1, GroupSpec((("a", "b"), ("p",)))),
]

OUT_DIR = Path(__file__).resolve().parents[1] / "docs" / "explorations"
TERM_LIMIT = 100

PREAMBLE = r"""\documentclass[10pt]{article}
\usepackage[a4paper,margin=2cm,landscape]{geometry}
\usepackage{amsmath,amssymb,longtable,array}
\setlength{\LTleft}{0pt}
\title{symembed: simple cases written out in full}
\date{\today}
\begin{document}
\maketitle

Each section shows one case. The slots of $w$ are listed with horizontal rules between $G$-orbits. Each group
element's action is shown as the row $g \cdot w$, which holds the coefficients of
$q_g(x) = \sum_j (g\cdot w)_j\, x^j$. Then every Bursarial output $E_{c,j}$, where
$\prod_g \bigl(y + q_g(x)\bigr) = \sum_c y^{|G| - c} \sum_j E_{c,j}\, x^j$, is shown expanded in the $d$'s and
$e$'s. The status column shows whether the safe reductions keep the output, and otherwise the exact identity used
to drop it. No determinants are omitted here, because no case contains parity. Expansions with more than
TERMLIMIT terms show only their term count. Every expansion appears in full in \texttt{simple\_cases\_full.txt}.
This file is generated by \texttt{symembed/explore/simple\_cases.py}; do not edit it by hand.

"""


def quotient_dimension(n: int, k: int) -> int:
    """dim of (R^k)^n / SO(k) for generic inputs: nk - dim SO(k) + dim SO(k - n) (the stabiliser, when n < k)."""
    def dim_so(r):
        return r * (r - 1) // 2 if r > 0 else 0
    return n * k - dim_so(k) + dim_so(k - n)


def _signed_slot(meta, g, j) -> str:
    s = meta.slots[meta.index[g][j]].latex(meta.labels)
    return ("-" if meta.sign[g][j] < 0 else "") + s


def case_section(title: str, k: int, spec: GroupSpec, full_text: list) -> str:
    _, meta = build_invariant_embedding(k, spec, EmbeddingOptions(dtype=torch.float64))
    _, safe = build_invariant_embedding(k, spec, EmbeddingOptions(reductions="safe", dtype=torch.float64))
    assert safe.base_output_labels == meta.base_output_labels and safe.slots == meta.slots
    expanded = meta.expanded_base_outputs()
    dropped = {r.dropped: r for r in safe.relations}
    L = spec.labels

    full_text += ["", "=" * 100, f"{title}   (n = {spec.n}, k = {k}, |G| = {meta.N}, m = {meta.m})",
                  "slots: " + ", ".join(meta.slot_names()), "=" * 100]
    lines = [f"\\section{{{title}}}",
             f"$n = {spec.n}$, $k = {k}$, $|G| = {meta.N}$, $m = {meta.m}$ slots. "
             f"Bursarial outputs: {len(meta.base_output_labels)}; after safe reductions: {safe.D} "
             f"(exact linear dependencies checked for $c \\le {safe.linear_reduction_max_c}$). "
             f"Quotient dimension (the minimum number of outputs, for generic inputs): "
             f"{quotient_dimension(spec.n, k)}.",
             ""]

    orbit_end = {run[-1] for run in slot_orbits(spec, meta.slots)}
    rows = [f"{j} & ${s.latex(L)}$ & {s.L_degree(k)} \\\\" + (" \\hline" if j in orbit_end else "")
            for j, s in enumerate(meta.slots)]
    lines += ["\\begin{longtable}{rcc}", "slot $j$ & $w_j$ & degree in $L$ \\\\ \\hline", *rows,
              "\\end{longtable}", ""]

    rows = [f"${g.cycle_notation(L)}$ & $(" + ",\\ ".join(_signed_slot(meta, r, j) for j in range(meta.m)) + ")$ \\\\"
            for r, g in enumerate(meta.elements)]
    lines += ["\\begin{longtable}{ll}", "$g$ & $g \\cdot w$ \\\\ \\hline", *rows, "\\end{longtable}", ""]

    for c in range(1, meta.N + 1):
        lines += [f"\\subsection*{{$c = {c}$}}",
                  "\\begin{longtable}{r>{\\raggedright\\arraybackslash}p{0.62\\textwidth}"
                  ">{\\raggedright\\arraybackslash}p{0.25\\textwidth}}",
                  "output & expanded & safe reductions \\\\ \\hline"]
        for b, (cc, j) in enumerate(meta.base_output_labels):
            if cc != c:
                continue
            expr = sympy.expand(expanded[b])
            n_terms = 0 if expr == 0 else len(sympy.Add.make_args(expr))
            if n_terms > TERM_LIMIT:
                body = f"\\text{{({n_terms} terms; see the full text file)}}"
            else:
                body = "0" if expr == 0 else sympy.latex(expr)
            if b in dropped:
                rhs = safe.relation_summary(dropped[b]).split(" = ", 1)[1]
                status = f"dropped: $= {rhs}$"
                text_status = f"dropped: = {rhs}"
            else:
                status = "kept"
                text_status = "kept"
            full_text.append(f"E_{{{c},{j}}}  [{text_status}]  ({n_terms} terms)  =  {sympy.sstr(expr)}")
            lines.append(f"$E_{{{c},{j}}}$ & $= {body}$ & {status} \\\\")
        lines += ["\\end{longtable}", ""]
    return "\n".join(lines)


def main(cases=CASES, out_dir: Path = OUT_DIR) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    tex = out_dir / "simple_cases.tex"
    sections, full_text = [], ["symembed: simple cases, every Bursarial output expanded in full.",
                               "Generated by symembed/explore/simple_cases.py; do not edit by hand."]
    for title, k, spec in cases:
        print(f"writing: {title}", file=sys.stderr)
        sections.append(case_section(title, k, spec, full_text))
    preamble = PREAMBLE.replace("TERMLIMIT", str(TERM_LIMIT))
    tex.write_text(preamble + "\n\\clearpage\n".join(sections) + "\n\\end{document}\n")
    (out_dir / "simple_cases_full.txt").write_text("\n".join(full_text) + "\n")
    if shutil.which("pdflatex"):
        for _ in range(2):
            subprocess.run(["pdflatex", "-interaction=nonstopmode", tex.name], cwd=out_dir,
                           capture_output=True, check=False)
        for suffix in (".aux", ".log", ".out"):
            (out_dir / ("simple_cases" + suffix)).unlink(missing_ok=True)
    return tex


if __name__ == "__main__":
    print(main())
