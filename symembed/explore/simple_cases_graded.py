"""
Write out, in full, the graded-packing embeddings of very simple cases, with exact coefficients.

Run from the repository root:

    /Users/lester/github/Echinocoder/venv/bin/python -m symembed.explore.simple_cases_graded

This writes symembed/docs/explorations/simple_cases_graded.tex (compiled to .pdf if pdflatex is available) and
simple_cases_graded_full.txt. Each case shows the chosen (h, s), the invariants output directly, the packed
coordinates (exactly, as complex linear forms in the d's and e's), and every output expanded in the d's and e's.
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
import sympy
import torch

from symembed import EmbeddingOptions, GroupSpec, build_invariant_embedding
from symembed.cyclotomic import Cyclotomic
from symembed.explore.simple_cases import CASES, OUT_DIR, TERM_LIMIT, quotient_dimension

PREAMBLE = r"""\documentclass[10pt]{article}
\usepackage[a4paper,margin=2cm,landscape]{geometry}
\usepackage{amsmath,amssymb,longtable,array}
\setlength{\LTleft}{0pt}
\title{symembed: graded packing of simple cases, written out in full}
\date{\today}
\begin{document}
\maketitle

Each section shows the graded embedding (\texttt{embedder="bursar\_graded"}, notes Section~3.4) of one case: the
chosen $h$ (order $r$) and $s$, the invariants output directly, the packed coordinates $z_j$ (exact complex linear
forms in the $d$'s and $e$'s, at power $x^j$, with their $h$-weights), and every output expanded in the $d$'s and
$e$'s with exact coefficients. Expansions with more than TERMLIMIT terms show only their term count; all appear in full
in \texttt{simple\_cases\_graded\_full.txt}. Generated by \texttt{symembed/explore/simple\_cases\_graded.py}; do not
edit by hand.

"""


def coordinate_forms(meta) -> list[tuple]:
    """Exact (weight, real part, imaginary part) of each packed coordinate, as sympy expressions."""
    p = meta.packing
    F = Cyclotomic(p.L)
    w = [sympy.Symbol(nm, real=True) for nm in meta.slot_names()]
    out = []
    for U, weight in zip(p.exact, p.weights):
        expr = sum((F.to_sympy(U[t]) * w[t] for t in range(meta.m) if np.any(U[t])), sympy.Integer(0))
        re, im = expr.as_real_imag()
        out.append((weight, sympy.simplify(re), sympy.simplify(im)))
    return out


def case_section(title: str, k: int, spec: GroupSpec, full_text: list) -> str:
    _, meta = build_invariant_embedding(k, spec, EmbeddingOptions(embedder="bursar_graded", dtype=torch.float64))
    p = meta.packing
    name = lambda g: "-" if g is None else meta.elements[g].cycle_notation(spec.labels)
    names = meta.output_names()
    expanded = meta.expanded_outputs()
    s_name = name(p.s) if p.s is not None else "\\text{none}"
    lines = [f"\\section{{{title}}}",
             f"$|G| = {meta.N}$, $m = {meta.m}$ slots; $h = {name(p.h)}$ (order $r = {p.r}$), "
             f"$s = {s_name}$, mode {p.mode}; "
             f"{'real' if p.real else 'complex'} coefficients. Outputs: {meta.D} "
             f"(plain Bursarial: {build_invariant_embedding(k, spec)[1].D}; quotient dimension "
             f"{quotient_dimension(spec.n, k)}).", ""]
    full_text += ["", "=" * 100, f"{title}   (|G| = {meta.N}, m = {meta.m}, h = {name(p.h)}, s = {name(p.s)}, "
                  f"r = {p.r}, mode = {p.mode}, D = {meta.D})", "=" * 100]
    if len(p.invariants):
        lines += ["Invariants output directly:", "\\begin{itemize}"]
        for t, row in enumerate(p.invariants):
            expr = sum((int(round(c)) * sympy.Symbol(nm) for c, nm in zip(row, meta.slot_names()) if abs(c) > 1e-12),
                       sympy.Integer(0))
            lines.append(f"  \\item inv[{t}] $= {sympy.latex(expr)}$")
        lines += ["\\end{itemize}", ""]
    rows = []
    for j, (weight, re, im) in enumerate(coordinate_forms(meta)):
        rows.append(f"{j} & {'' if weight is None else weight} & ${sympy.latex(re)}$ & ${sympy.latex(im)}$ \\\\")
        full_text.append(f"z_{j} (weight {weight}) = ({sympy.sstr(re)}) + i ({sympy.sstr(im)})")
    lines += ["\\begin{longtable}{rr>{\\raggedright\\arraybackslash}p{0.4\\textwidth}"
              ">{\\raggedright\\arraybackslash}p{0.4\\textwidth}}",
              "$j$ & weight & real part of $z_j$ & imaginary part of $z_j$ \\\\ \\hline", *rows, "\\end{longtable}", ""]
    rows = []
    for nm, expr in zip(names, expanded):
        n_terms = 0 if expr == 0 else len(sympy.Add.make_args(expr))
        body = f"\\text{{({n_terms} terms; see the full text file)}}" if n_terms > TERM_LIMIT else sympy.latex(expr)
        rows.append(f"${nm}$ & ${body}$ \\\\")
        full_text.append(f"{nm}  ({n_terms} terms)  =  {sympy.sstr(expr)}")
    lines += ["\\begin{longtable}{r>{\\raggedright\\arraybackslash}p{0.85\\textwidth}}", "output & expanded \\\\ \\hline",
              *rows, "\\end{longtable}", ""]
    return "\n".join(lines)


def main(cases=CASES, out_dir: Path = OUT_DIR) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    tex = out_dir / "simple_cases_graded.tex"
    sections, full_text = [], ["symembed: graded packing of simple cases, every output expanded in full.",
                               "Generated by symembed/explore/simple_cases_graded.py; do not edit by hand."]
    for title, k, spec in cases:
        print(f"writing: {title}", file=sys.stderr)
        sections.append(case_section(title, k, spec, full_text))
    tex.write_text(PREAMBLE.replace("TERMLIMIT", str(TERM_LIMIT)) + "\n\\clearpage\n".join(sections)
                   + "\n\\end{document}\n")
    (out_dir / "simple_cases_graded_full.txt").write_text("\n".join(full_text) + "\n")
    if shutil.which("pdflatex"):
        for _ in range(2):
            subprocess.run(["pdflatex", "-interaction=nonstopmode", tex.name], cwd=out_dir, capture_output=True,
                           check=False)
        for suffix in (".aux", ".log", ".out"):
            (out_dir / ("simple_cases_graded" + suffix)).unlink(missing_ok=True)
    return tex


if __name__ == "__main__":
    print(main())
