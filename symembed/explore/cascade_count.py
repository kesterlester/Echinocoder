"""
Exact output counts for the cascaded graded construction on a dihedral group D_r = <h, s> (|G| = 2r, G = D_r):
stage i embeds the orbit of the current coordinates under a cyclic factor Z_p of the remaining rotation group, with
positions = weight + shift (mod R) so that the rest acts by substitutions; the last stage handles s (conjugation):
Re part output directly, Im part up to sign by squaring.
"""
import itertools, sys
sys.path.insert(0, ".")                  # run from the repository root
from symembed import GroupSpec, EmbeddingOptions, build_invariant_embedding
from symembed.graded import choose_layout


def cyclic_stage(weights, R, p):
    """weights: list of weights (mod R) of complex coordinates (conj allowed: weight -> -weight).
    Returns the list of new weights (mod R/p) after embedding the Z_p-orbit (Z_p generated by g^(R/p))."""
    passed = [k // p for k in weights if k % p == 0]          # Z_p-invariant: passed through, weight k/p mod R/p
    packed = [k for k in weights if k % p != 0]
    if not packed:
        return [k % (R // p) for k in passed]
    # layout mod R: real weights (0, R/2) fixed; pairs {k, R-k} may be swapped by conjugation
    real, pairs = {}, {}
    for k in packed:
        if k == 0 or 2 * k == R:
            real[k] = real.get(k, 0) + 1
        else:
            kk = min(k, R - k)
            pairs[kk] = pairs.get(kk, 0) + 1
    shift, counts = choose_layout(R, real, pairs)
    occupied = sorted({(rho + shift) % R + R * t for rho, n in counts.items() for t in range(n)})
    W = max(occupied) + 1
    out = list(passed)
    reach = {0}
    for c in range(1, p + 1):
        reach = {a + b for a in reach for b in occupied}
        for j in sorted(reach):
            if (j - shift * c) % p == 0:
                out.append(((j - shift * c) // p) % (R // p))
    return [k % (R // p) for k in out]


def cascade(weights, r, order, real_structure=True):
    """order: list of cyclic factors (product r). Returns the number of real outputs (excluding invariants)."""
    R, ws = r, list(weights)
    for p in order:
        ws = cyclic_stage(ws, R, p)
        R //= p
    K = len(ws)                                                  # complex coordinates, all rotation-invariant
    return K + (2 * K - 1) if real_structure else 2 * K


def factorisations(r):
    if r == 1:
        yield []
        return
    for p in range(2, r + 1):
        if r % p == 0:
            for rest in factorisations(r // p):
                yield [p] + rest


