    S = lambda *sp, parity=False: GroupSpec(tuple(tuple(x) for x in sp), parity=parity)
    for k, spec, reds in [(4, S("abc", "pq"), "none"), (3, S("abc", "pq"), "none"), (2, S("abc", "pq"), "none"),
                          (4, S("abc", "pq", parity=True), "safe"), (2, S("abc"), "none"), (3, S("abc"), "none"),
                          (2, S("ab", "pq"), "none"), (3, S("ab", "pq"), "none")]:
        _, meta = build_invariant_embedding(k, spec, EmbeddingOptions(embedder="bursar_graded", reductions=reds))
        p = meta.packing
        if 2 * p.r != meta.N or p.s is None:
            print(spec.species, k, "G is not the dihedral group used; skipped", meta.N, p.r)
            continue
