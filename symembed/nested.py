"""
Nested coset packing (notes, Section 3.5).

For a subgroup H of G, the multiset MS = {g.w : g in G} is the disjoint union, over right cosets Hg, of the H-orbits
H.(g.w). So MS is determined by the multiset of those |G|/|H| H-orbits. Each H-orbit is embedded injectively by a graded
packing for H (inner), and the multiset of the resulting vectors by a plain Bursarial embedding (outer). Both stages
are injective on the multisets they receive, so the result is injective on MS (Level 0).

The outer Bursarial cost is quadratic in the number of cosets, so for a dihedral H of order 2r the total is roughly
half that of the flat graded packing when there are many cosets, and worse when there are few. ``choose_nested``
therefore also reports the flat graded count, and the build uses whichever is smaller.
"""
from __future__ import annotations

import json

import numpy as np
import torch

from .bursar import bursar_coefficients, bursar_output_labels, bursar_size
from .graded import GradedEmbedding, choose_packing, conjugacy_key, matrices
from .meta import CERTIFICATION_E_DROPPED, SYMEMBED_VERSION, _echinocoder_commit, _latex_text
from .module import InvariantEmbedding


def _key(M) -> tuple:
    idx = np.argmax(np.abs(M), axis=1)
    return tuple(int(i) for i in idx), tuple(int(round(M[i, j])) for i, j in enumerate(idx))


def subgroup(Ms: list, gens: list) -> list[int]:
    """Indices (into Ms) of the subgroup generated by ``gens``; element 0 must be the identity."""
    key_of = {_key(M): g for g, M in enumerate(Ms)}
    seen, frontier = {0}, [0]
    while frontier:
        new = []
        for a in frontier:
            for b in gens:
                c = key_of[_key(Ms[a] @ Ms[b])]
                if c not in seen:
                    seen.add(c)
                    new.append(c)
        frontier = new
    return sorted(seen)


def right_coset_representatives(Ms: list, H: list) -> list[int]:
    """One representative g for each set {M_h M_g : h in H} (these sets partition the matrix group)."""
    key_of = {_key(M): g for g, M in enumerate(Ms)}
    seen, reps = set(), []
    for g in range(len(Ms)):
        coset = frozenset(key_of[_key(Ms[h] @ Ms[g])] for h in H)
        if coset not in seen:
            seen.add(coset)
            reps.append(g)
    return reps


def choose_nested(index: list, sign: list, elements: tuple, species_blocks):
    """
    Search dihedral subgroups H = <h, s> (one h per conjugacy class, a few s per h) for the smallest nested count.
    Returns (count, H, inner packing) for the best, or None if no proper subgroup is found.
    """
    Ms = matrices(index, sign)
    N, I = len(Ms), np.eye(Ms[0].shape[0])
    involutions = [g for g in range(N) if np.allclose(Ms[g] @ Ms[g], I)]
    candidates, seen = {}, set()
    for h, element in enumerate(elements):
        key = conjugacy_key(element, species_blocks)
        if key in seen:
            continue
        seen.add(key)
        partners = [x for x in involutions if np.allclose(Ms[x] @ Ms[h] @ Ms[x], Ms[h].T)][:4] + [None]
        for s in partners:
            H = tuple(subgroup(Ms, [h] + ([] if s is None else [s])))
            candidates.setdefault(H, None)
    best = None
    for H in candidates:
        if len(H) in (1, N):
            continue
        packing = choose_packing([index[g] for g in H], [sign[g] for g in H], tuple(elements[g] for g in H),
                                 species_blocks)
        count = bursar_size(N // len(H), packing.output_count(len(H)))
        if best is None or count < best[0]:
            best = (count, list(H), packing)
    return best


class NestedEmbedding(InvariantEmbedding):
    """Inner graded packing on each H-orbit H.(g.w) (one per right coset), outer plain Bursar over the cosets."""

    def __init__(self, n: int, k: int, slots: tuple, index: list, sign: list, dtype: torch.dtype, H: list,
                 reps: list, inner_packing, metric: tuple | None = None):
        super().__init__(n, k, slots, [index[g] for g in reps], [sign[g] for g in reps], dtype, metric=metric)
        self.inner = GradedEmbedding(n, k, slots, [index[h] for h in H], [sign[h] for h in H], dtype,
                                     inner_packing, metric=metric)
        self.n_cosets = len(reps)
        self.inner_D = int(self.inner.output_shape.item())
        self.output_shape = torch.tensor([bursar_size(self.n_cosets, self.inner_D)], dtype=torch.int64)

    def forward(self, x) -> torch.Tensor:
        x = self._prepare(x)
        batch_shape = x.shape[:-2]
        w = self.w(x).reshape(-1, self.m)
        B = w.shape[0]
        w_reps = w[:, self.g_index] * self.g_sign                          # (B, cosets, m): g_rep . w
        inner = self.inner.from_w(w_reps.reshape(B * self.n_cosets, self.m)).reshape(B, self.n_cosets, self.inner_D)
        out = bursar_coefficients(inner)
        return out.reshape(*batch_shape, out.shape[-1])


CERTIFICATION_NESTED = (
    "Level 0 (by construction): nested coset packing. MS is the disjoint union over right cosets Hg of the H-orbits "
    "H.(g.w), so it is determined by the multiset of these orbits. Each H-orbit is embedded injectively by a graded "
    "packing for H (Level 0, see its own certificate), and the multiset of the resulting vectors by the Bursarial "
    "embedding (injective on multisets by unique factorisation). MS determines L up to G and rotations (up to G and "
    "O(k) if parity is in G; see the notes on indefinite metrics)."
)


class NestedMeta:
    """Metadata for embedder="bursar_nested" when nesting is used (same reading API as EmbeddingMeta)."""

    def __init__(self, group_spec, k, options, slots, elements, H, reps, inner_meta, e_dropped: bool):
        self.group_spec, self.k, self.options, self.slots = group_spec, k, options, slots
        self.elements, self.H, self.reps, self.inner, self.e_dropped = elements, H, reps, inner_meta, e_dropped
        self.relations = ()
        self.kept = list(range(self.D))
        self.echinocoder_commit = _echinocoder_commit()

    certification_level = 0
    labels = property(lambda self: self.group_spec.labels)
    n = property(lambda self: self.group_spec.n)
    m = property(lambda self: len(self.slots))
    N = property(lambda self: len(self.elements))

    @property
    def D(self) -> int:
        return bursar_size(len(self.reps), self.inner.D)

    @property
    def certification(self) -> str:
        return CERTIFICATION_NESTED + (" " + CERTIFICATION_E_DROPPED if self.e_dropped else "")

    def slot_names(self) -> list[str]:
        return [s.name(self.labels) for s in self.slots]

    def output_names(self) -> list[str]:
        return [f"outer E_{{{c},{j}}}" for c, j in bursar_output_labels(len(self.reps), self.inner.D)]

    def reconstruct_base(self, Y):
        return Y

    def to_dict(self) -> dict:
        name = lambda g: self.elements[g].cycle_notation(self.labels)
        return {
            "symembed_version": SYMEMBED_VERSION, "echinocoder_commit": self.echinocoder_commit,
            "group_spec": self.group_spec.to_dict(), "k": self.k, "options": self.options.to_dict(),
            "n": self.n, "m": self.m, "multiset_size": self.N, "D": self.D,
            "certification_level": 0, "certification": self.certification,
            "nested": {"H": [name(g) for g in self.H], "order_H": len(self.H),
                       "coset_representatives": [name(g) for g in self.reps],
                       "inner_D": self.inner.D, "inner": self.inner.to_dict(),
                       "meaning": "outputs = Bursarial coefficients of the multiset, over right cosets Hg, of the "
                                  "inner graded embedding of the H-orbit H.(g.w)"},
            "outputs": [{"index": i, "name": nm} for i, nm in enumerate(self.output_names())],
        }

    def to_json(self, **kwargs) -> str:
        return json.dumps(self.to_dict(), **kwargs)

    def latex(self, max_rows: int = 200) -> str:
        name = lambda g: self.elements[g].cycle_notation(self.labels)
        head = (f"\\noindent Nested coset packing: $n = {self.n}$, $k = {self.k}$, $|G| = {self.N}$, subgroup $H$ of "
                f"order {len(self.H)} (elements ${', '.join(name(g) for g in self.H)}$), {len(self.reps)} right "
                f"cosets, inner dimension {self.inner.D}, $D = {self.D}$ outputs. "
                f"Certification: {_latex_text(self.certification)}\n\n")
        return head + "\\medskip\\noindent Inner embedding (for one coset):\n\n" + self.inner.latex(max_rows)
